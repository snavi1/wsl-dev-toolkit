#!/usr/bin/env bash
#
# =============================================================================
# WSL Developer Toolkit
# Common Library
# =============================================================================

set -o errexit
set -o nounset
set -o pipefail

# -----------------------------------------------------------------------------
# Print Toolkit Header
# -----------------------------------------------------------------------------

print_header() {

    echo
    echo "========================================="
    printf "      %s\n" "$1"
    echo "========================================="
    echo
}

# -----------------------------------------------------------------------------
# Print Section Header
# -----------------------------------------------------------------------------

print_section() {

    echo
    echo "========================================="
    echo "$1"
    echo "========================================="
}

# -----------------------------------------------------------------------------
# Print Key-Value Pair
# -----------------------------------------------------------------------------

print_kv() {

    printf "%-18s : %s\n" "$1" "$2"
}

# -----------------------------------------------------------------------------
# Logging Helpers
# -----------------------------------------------------------------------------

log_info() {

    printf "[INFO] %s\n" "$1"
}

log_warn() {

    printf "[WARN] %s\n" "$1"
}

log_error() {

    printf "[ERROR] %s\n" "$1"
}

# -----------------------------------------------------------------------------
# Fatal Error
# -----------------------------------------------------------------------------

die() {

    log_error "$1"
    exit 1
}

###############################################################################
# Check whether a command exists in PATH.
###############################################################################

require_command() {

    command -v "$1" >/dev/null 2>&1
}

# -----------------------------------------------------------------------------
# Check Command Availability
# -----------------------------------------------------------------------------

check_command() {

    local name="$1"
    local cmd="$2"

    if command -v "$cmd" >/dev/null 2>&1; then
        printf "[ OK ] %-15s found\n" "$name"
    else
        printf "[FAIL] %-15s NOT found\n" "$name"
    fi
}

# -----------------------------------------------------------------------------
# Toolkit Version
# -----------------------------------------------------------------------------

get_version() {

    cat "$PROJECT_ROOT/VERSION"
}
